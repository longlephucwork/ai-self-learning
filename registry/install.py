#!/usr/bin/env python3
"""Phase 4: install approved artifacts and keep the registry. Every change is a git commit.

Called by `review/cli.py approve|reject` (which owns the human-approval gate);
it can also be run directly for listing and uninstalling:

  install.py list
  install.py uninstall <name> [--reason TEXT]
  install.py shims                 (re)create bin/<name> wrappers for installed scripts

Install locations, relative to the install root: learned/ in this repo (its own local git repo, which
the code repo ignores, so learned items are never pushed), or $LEARNING_HARNESS_INSTALL_ROOT:
  script -> scripts/<name>/  plus a usage-logging wrapper bin/<name>   run with: bin/<name> ...
  skill  -> skills/<name>/ + symlink ~/.claude/skills/<name> -> it   (git stays the source of truth)
  tool   -> mcp_tools/tools/<name>/  (tool.json + any code), served by mcp_tools/server.py as mcp__learned__<name>
registry.json records what is installed, which version, from which pattern and evidence.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from harness_lib import store  # noqa: E402


COPY_MARKER = ".learning-harness-copy"


class InstallError(RuntimeError):
    pass


def install_root() -> Path:
    return store.learned_dir().resolve()


def ensure_learned_repo() -> None:
    """Create learned/ as its own git repo on first use (only for the default location)."""
    if "LEARNING_HARNESS_INSTALL_ROOT" in os.environ:
        return
    root = install_root()
    if (root / ".git").exists():
        return
    root.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", str(root)], check=True, capture_output=True)
    (root / "README.md").write_text("# learned\n\nWhat the learning harness learned on this machine. A local git repo: "
                                    "every install, revision and rejection is a commit. Never pushed with the code.\n",
                                    encoding="utf-8")


def _link_skill(dest: Path, link: Path) -> None:
    """Make ~/.claude/skills/<name> point at the installed skill (a marked copy where symlinks aren't allowed)."""
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.exists() and (link / COPY_MARKER).exists():
        shutil.rmtree(link)  # our earlier copy; refresh it
    if not link.is_symlink() and not link.exists():
        try:
            link.symlink_to(dest.resolve(), target_is_directory=True)
        except OSError:
            # Windows without developer mode can't create symlinks: install a marked copy instead.
            shutil.copytree(dest, link)
            (link / COPY_MARKER).write_text(f"copy of {dest}; managed by learning-harness\n", encoding="utf-8")


def relink_skills() -> list[str]:
    """Repair: link every installed skill that Claude Code can't currently see. Returns the names fixed."""
    fixed = []
    reg = load_registry()
    for e in reg["installed"].values():
        if e["type"] != "skill":
            continue
        dest = install_root() / e["path"]
        link = skills_link_dir() / e["name"]
        if not (dest / "SKILL.md").is_file():
            continue
        ours = (link.is_symlink() and link.resolve() == dest.resolve()) or (link / COPY_MARKER).exists()
        if link.is_symlink() and not link.exists():
            link.unlink()  # dangling (e.g. the repo moved)
        elif link.exists() and not ours:
            continue       # someone else's folder of that name; leave it
        if ours:
            continue       # linked already (a Windows copy is refreshed by install() on each new version)
        _link_skill(dest, link)
        if e.get("symlink") != str(link):
            e["symlink"] = str(link)
            store.write_json_atomic(registry_path(), reg)
        fixed.append(e["name"])
    return fixed


def skills_link_dir() -> Path:
    return Path(os.environ.get("LEARNING_HARNESS_SKILLS_DIR", Path.home() / ".claude" / "skills"))


SHIM = """#!/usr/bin/env python3
# learning-harness usage wrapper for the installed script '{name}' (v{version}).
# Generated by registry/install.py (harness code, not learned code). It runs the
# script unchanged, then appends ONE line to store/usage/{name}.jsonl:
# time, exit code, duration, version, and whether Claude Code ran it (with its
# session id). It never records arguments, file contents or output.
import json, os, subprocess, sys, time
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))   # the learned/ folder
ENTRY = os.path.join(ROOT, {entry!r})
t0 = time.time()
rc = subprocess.call([sys.executable, ENTRY] + sys.argv[1:])
try:
    store = os.environ.get("LEARNING_HARNESS_STORE") or os.path.normpath(os.path.join(ROOT, {store_rel!r}))
    os.makedirs(os.path.join(store, "usage"), exist_ok=True)
    rec = {{"name": {name!r}, "version": {version}, "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
           "exit": rc, "duration_ms": int((time.time() - t0) * 1000),
           "via": "claude" if os.environ.get("CLAUDECODE") == "1" else "terminal",
           "session_id": os.environ.get("CLAUDE_CODE_SESSION_ID")}}
    fd = os.open(os.path.join(store, "usage", {name!r} + ".jsonl"), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o644)
    os.write(fd, (json.dumps(rec) + "\\n").encode())
    os.close(fd)
except Exception:
    pass  # logging must never break the script
sys.exit(rc)
"""


def shim_path(name: str) -> Path:
    return install_root() / "bin" / name


CMD_SHIM = """@echo off
rem learning-harness usage wrapper for '{name}' on Windows: runs bin\\{name} with Python.
if defined LEARNING_HARNESS_PYTHON (
  "%LEARNING_HARNESS_PYTHON%" "%~dp0{name}" %*
) else (
  python "%~dp0{name}" %*
)
exit /b %ERRORLEVEL%
"""


def write_shim(entry: dict) -> Path:
    """bin/<name> (Python, used directly on Linux/macOS) and bin/<name>.cmd (Windows)."""
    p = shim_path(entry["name"])
    p.parent.mkdir(parents=True, exist_ok=True)
    store_rel = os.path.relpath(store.store_dir().resolve(), install_root()).replace(os.sep, "/")
    p.write_text(SHIM.format(name=entry["name"], version=entry["version"], store_rel=store_rel,
                             entry=f"{entry['path']}/{entry['entrypoint']}"), encoding="utf-8")
    os.chmod(p, 0o755)
    with open(p.with_name(p.name + ".cmd"), "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write(CMD_SHIM.format(name=entry["name"]))
    return p


def registry_path() -> Path:
    return install_root() / "registry.json"


def load_registry() -> dict:
    return store.read_json(registry_path()) or {"format_version": 1, "installed": {}, "history": []}


def _save_registry(reg: dict) -> None:
    store.write_json_atomic(registry_path(), reg)


def _rel(p: Path) -> str:
    """Repo-relative path when inside the install root, so the repo can be moved or re-cloned."""
    p = Path(p).resolve()
    try:
        return p.relative_to(install_root()).as_posix()
    except ValueError:
        return str(p)


def resolve(p: str) -> Path:
    q = Path(p)
    return q if q.is_absolute() else install_root() / q


def file_hashes(files: dict[str, str]) -> dict[str, str]:
    return {p: hashlib.sha256(c.encode("utf-8")).hexdigest()[:16] for p, c in sorted(files.items())}


# ---------------- git ----------------

def _git(*args, check=True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(install_root()), *_identity(), *args], capture_output=True, text=True,
                          check=check)


def _identity() -> list[str]:
    """Commit as you if git knows who you are; otherwise as `learning-harness`, instead of failing."""
    have = subprocess.run(["git", "-C", str(install_root()), "config", "user.email"], capture_output=True,
                          text=True).stdout.strip() or os.environ.get("GIT_COMMITTER_EMAIL")
    return [] if have else ["-c", "user.name=learning-harness", "-c", "user.email=learning-harness@localhost"]


def git_available() -> bool:
    try:
        ensure_learned_repo()
        return _git("rev-parse", "--is-inside-work-tree", check=False).stdout.strip() == "true"
    except FileNotFoundError:
        return False


def git_commit(paths: list[Path], message: str) -> str | None:
    """Commit only `paths` (adds, modifications and deletions); leaves anything else alone."""
    root = install_root()
    rels = []
    for p in paths:
        p = Path(p).resolve()
        try:
            rels.append(p.relative_to(root).as_posix())
        except ValueError:
            continue  # outside the repo (e.g. the ~/.claude/skills symlink); not versioned
    # keep paths that exist now, or that git tracks (i.e. deletions); drop ones that never existed
    tracked = set(_git("ls-files", "--", *rels).stdout.split()) if rels else set()
    rels = [r for r in rels if (root / r).exists() or any(t == r or t.startswith(r.rstrip("/") + "/") for t in tracked)]
    if not rels:
        return None
    _git("add", "-A", "--", *rels)
    if not _git("diff", "--cached", "--quiet", "--", *rels, check=False).returncode:
        return None  # nothing changed
    _git("commit", "-q", "-m", message, "--", *rels)
    return _git("rev-parse", "--short", "HEAD").stdout.strip()


# ---------------- install / uninstall ----------------

def target_dir(kind: str, name: str) -> Path:
    if kind == "script":
        return install_root() / "scripts" / name
    if kind == "skill":
        return install_root() / "skills" / name
    if kind == "tool":
        return install_root() / "mcp_tools" / "tools" / name
    raise InstallError(f"unknown artifact type {kind!r}")


def install(proposal: dict, files: dict[str, str], *, draft_dir: Path, note: str | None,
            validation: dict, use_git: bool = True) -> dict:
    """Install exactly `files` (the bytes that were just validated). Caller has the human approval."""
    if use_git and not git_available():
        raise InstallError(f"{install_root()} is not a git repository; refusing to install without "
                           f"versioning (pass --no-git to override)")
    name, kind = proposal["name"], proposal["type"]
    dest = target_dir(kind, name)
    reg = load_registry()
    prev = reg["installed"].get(name)
    if prev and prev["pattern_key"] != proposal["pattern_key"]:
        raise InstallError(f"{name!r} is already installed from another pattern ({prev['pattern_key']})")
    if prev and prev["type"] != kind:
        raise InstallError(f"{name!r} is already installed as a {prev['type']}")
    if proposal.get("wraps"):
        wrapped = reg["installed"].get(proposal["wraps"]["script"])
        if not wrapped or wrapped["type"] != "script":
            raise InstallError(f"tool wraps {proposal['wraps']['script']!r}, which is not an installed script")
    link = None
    if kind == "skill":
        link = skills_link_dir() / name
        ours = (link.is_symlink() and link.resolve() == dest.resolve()) or (link / COPY_MARKER).exists()
        if (link.exists() or link.is_symlink()) and not ours:
            raise InstallError(f"{link} already exists and is not ours; not overwriting it")

    # Write the new version into place (replace the folder wholesale; git keeps the old one).
    tmp = dest.with_name(f".{name}.installing")
    shutil.rmtree(tmp, ignore_errors=True)
    for p, c in files.items():
        fp = tmp / p
        fp.parent.mkdir(parents=True, exist_ok=True)
        fp.write_text(c, encoding="utf-8")
    if kind == "script":
        os.chmod(tmp / proposal["entrypoint"], 0o755)
    if dest.exists():
        shutil.rmtree(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    store._replace(str(tmp), dest)  # retried on Windows (e.g. a virus scanner holding the folder)
    if link is not None:
        _link_skill(dest, link)

    pattern = store.load_pattern(proposal["pattern_key"]) or {}
    entry = {
        "name": name, "type": kind, "pattern_key": proposal["pattern_key"],
        "version": (prev or {}).get("version", 0) + 1,
        "path": dest.relative_to(install_root()).as_posix(),
        "entrypoint": proposal.get("entrypoint"),
        "symlink": str(link) if link else None,
        "description": proposal["description"],
        "files": file_hashes(files),
        "evidence": {"n_sessions": pattern.get("n_sessions"), "n_success": pattern.get("n_success"),
                     "sessions": proposal["evidence"]["sessions"]},
        "tests_passed": sum(t["passed"] for t in validation.get("tests", [])),
        "tests_total": len(validation.get("tests", [])),
        "approved_at": store.now(), "approval_note": note,
        "draft": _rel(draft_dir),
    }
    if proposal.get("wraps"):
        entry["wraps"] = proposal["wraps"]["script"]
    if proposal.get("promotes"):
        entry["promoted_from"] = proposal["promotes"]  # the skill this replaced (for `refine.py demote`)
    if proposal.get("quick"):
        entry["quick"] = True
    if kind == "script":
        entry["shim"] = write_shim(entry).relative_to(install_root()).as_posix()
    reg["installed"][name] = entry
    reg["history"].append({"event": "install", "name": name, "version": entry["version"], "at": entry["approved_at"],
                           "note": note})
    _save_registry(reg)

    if pattern:
        pattern["status"] = "installed"
        pattern["installed"] = {"name": name, "version": entry["version"], "at": entry["approved_at"]}
        pattern.pop("pending_revision" if kind != "tool" or not proposal.get("wraps") else "pending_exposure", None)
        if proposal.get("promotes"):
            pattern.pop("pending_promotion", None)
        store.save_pattern(pattern)
    meta = store.read_json(draft_dir / "proposal.json")
    meta["status"] = "installed"
    meta["decision"] = {"decision": "approved", "at": entry["approved_at"], "note": note}
    store.write_json_atomic(draft_dir / "proposal.json", meta)

    if use_git:
        verb = "update" if prev else "install"
        msg = (f"learned: {verb} {kind} {name} v{entry['version']}\n\n"
               f"Pattern: {proposal['pattern_key']} (seen {pattern.get('n_sessions')} times, "
               f"{pattern.get('n_success')} successful)\n"
               f"Tests: {entry['tests_passed']}/{entry['tests_total']} passed in sandbox\n"
               f"Approved by a human via review/cli.py" + (f": {note}" if note else ""))
        paths = [dest, registry_path(), store.patterns_dir() / f"{proposal['pattern_key']}.json", draft_dir]
        if entry.get("shim"):
            paths += [install_root() / entry["shim"], install_root() / (entry["shim"] + ".cmd")]
        entry["commit"] = git_commit(paths, msg)
    return entry


def reject(proposal: dict, *, draft_dir: Path, reason: str, use_git: bool = True) -> str | None:
    ts = store.now()
    pattern = store.load_pattern(proposal["pattern_key"])
    if pattern:
        pattern["status"] = "rejected"
        pattern["rejected"] = {"at": ts, "reason": reason, "draft": proposal["name"],
                               "n_success_at_rejection": pattern.get("n_success")}
        store.save_pattern(pattern)
    meta = store.read_json(draft_dir / "proposal.json")
    meta["status"] = "rejected"
    meta["decision"] = {"decision": "rejected", "at": ts, "note": reason}
    store.write_json_atomic(draft_dir / "proposal.json", meta)
    if use_git and git_available():
        return git_commit([store.patterns_dir() / f"{proposal['pattern_key']}.json", draft_dir],
                          f"learned: reject {proposal['type']} {proposal['name']}\n\nReason: {reason}")
    return None


def uninstall(name: str, *, reason: str | None = None, use_git: bool = True, force: bool = False) -> str | None:
    reg = load_registry()
    if name not in reg["installed"]:
        raise InstallError(f"{name!r} is not installed")
    users = [e["name"] for e in reg["installed"].values() if e.get("wraps") == name]
    if users and not force:
        raise InstallError(f"{name!r} is used by installed tool(s) {users}; uninstall those first (or pass --force)")
    entry = reg["installed"].pop(name)
    dest = install_root() / entry["path"]
    if entry.get("symlink"):
        link = Path(entry["symlink"])
        if link.is_symlink():
            link.unlink()
        elif link.is_dir() and (link / COPY_MARKER).exists():
            shutil.rmtree(link)
    shutil.rmtree(dest, ignore_errors=True)
    shim = shim_path(name)
    for f in (shim, shim.with_name(shim.name + ".cmd")):
        if f.exists():
            f.unlink()
    reg["history"].append({"event": "uninstall", "name": name, "version": entry["version"], "at": store.now(),
                           "note": reason})
    _save_registry(reg)
    pattern = store.load_pattern(entry["pattern_key"])
    still_installed = [e["name"] for e in reg["installed"].values() if e["pattern_key"] == entry["pattern_key"]]
    if pattern and not still_installed:  # another item (e.g. the tool a skill was promoted to) keeps it alive
        pattern["status"] = "retired"
        pattern["retired"] = {"at": store.now(), "reason": reason}
        store.save_pattern(pattern)
    if use_git and git_available():
        return git_commit([dest, shim, shim.with_name(shim.name + ".cmd"), registry_path(), store.patterns_dir() / f"{entry['pattern_key']}.json"],
                          f"learned: uninstall {entry['type']} {name}" + (f"\n\nReason: {reason}" if reason else ""))
    return None


def session_start_context() -> str | None:
    """Every session: tell Claude which learned scripts exist and exactly how to run them.

    Skills and MCP tools are listed by Claude Code itself; scripts aren't, so without this Claude would
    redo the job by hand. Absolute paths, so it works even when Claude Code didn't inherit the PATH change."""
    scripts = [e for e in load_registry()["installed"].values() if e["type"] == "script" and e.get("shim")]
    if not scripts:
        return None
    lines = ["[learning-harness] Scripts learned from this user's own work and approved by them. When a task "
             "matches one, run it instead of doing the job by hand (it does exactly what the user accepted before; "
             "add --help to see its arguments):"]
    for e in sorted(scripts, key=lambda e: e["name"])[:20]:
        cmd = install_root() / (e["shim"] + (".cmd" if os.name == "nt" else ""))
        lines.append(f"- {e['name']}: {e['description'][:160]}  Run: {cmd.as_posix()} ARGS")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    p = sub.add_parser("uninstall"); p.add_argument("name"); p.add_argument("--reason")
    p.add_argument("--no-git", action="store_true"); p.add_argument("--force", action="store_true")
    p = sub.add_parser("shims"); p.add_argument("--no-git", action="store_true")
    a = ap.parse_args(argv)
    if a.cmd == "shims":
        reg = load_registry()
        paths = []
        for e in reg["installed"].values():
            if e["type"] == "script":
                e.pop("usage", None)  # superseded by store/usage/<name>.jsonl
                e["shim"] = write_shim(e).relative_to(install_root()).as_posix()
                paths += [install_root() / e["shim"], install_root() / (e["shim"] + ".cmd")]
                print(f"wrote {e['shim']}")
        _save_registry(reg)
        if paths and not a.no_git and git_available():
            c = git_commit(paths + [registry_path()], "learned: add usage-logging wrappers (bin/) for installed scripts")
            print(f"commit {c}" if c else "no changes")
        return 0
    if a.cmd == "list":
        reg = load_registry()
        if not reg["installed"]:
            print("nothing installed")
        for e in reg["installed"].values():
            print(f"{e['type']:7} {e['name']:24} v{e['version']}  {e['path']}  "
                  f"(pattern {e['pattern_key']}, approved {e['approved_at'][:10]})")
        return 0
    try:
        c = uninstall(a.name, reason=a.reason, use_git=not a.no_git, force=a.force)
    except InstallError as e:
        sys.exit(f"error: {e}")
    print(f"uninstalled {a.name}" + (f" (commit {c})" if c else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
